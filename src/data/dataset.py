"""
AgriAI — M1.5: PlantVillage PyTorch Dataset and DataLoader Utilities
Loads images using split manifests (CSV) generated by M1.4.
Enforces:
- Training augmentation on Train split ONLY.
- Deterministic transforms on Val / Test splits.
- Thread-safe loading with error handling.
"""

from pathlib import Path
from typing import Optional, Callable, Dict, Tuple
import pandas as pd
from PIL import Image
import torch
from torch.utils.data import Dataset, DataLoader

from .transforms import get_train_transforms, get_eval_transforms

class PlantVillageDataset(Dataset):
    """
    PyTorch Dataset for PlantVillage Tomato leaf images.
    Reads image paths and class targets from a split CSV manifest.
    """
    def __init__(
        self,
        manifest_csv: str or Path,
        root_dir: str or Path = "d:/Leaf",
        transform: Optional[Callable] = None
    ):
        self.manifest_path = Path(manifest_csv)
        self.root_dir = Path(root_dir)
        self.df = pd.read_csv(self.manifest_path)
        self.transform = transform
        
        # Verify required columns
        required_cols = {"filepath", "class_idx", "class_name"}
        if not required_cols.issubset(self.df.columns):
            raise ValueError(f"Manifest {manifest_csv} missing required columns: {required_cols - set(self.df.columns)}")

    def __len__(self) -> int:
        return len(self.df)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int]:
        row = self.df.iloc[idx]
        rel_path = row["filepath"]
        img_path = self.root_dir / rel_path
        
        try:
            image = Image.open(img_path).convert("RGB")
        except Exception as e:
            raise RuntimeError(f"Error loading image {img_path}: {e}")

        if self.transform is not None:
            image = self.transform(image)

        label = int(row["class_idx"])
        return image, label

    @property
    def classes(self):
        """Returns sorted unique class names."""
        sub = self.df.drop_duplicates(subset=["class_idx"]).sort_values("class_idx")
        return list(sub["class_name"])

def create_dataloaders(
    data_dir: str or Path = "d:/Leaf/data",
    image_size: int = 128,
    batch_size: int = 32,
    num_workers: int = 0,
    include_vertical_flip: bool = False
) -> Dict[str, DataLoader]:
    """
    Creates Train, Validation, and Test DataLoaders from split CSVs.
    
    Args:
        data_dir: Directory containing train.csv, val.csv, test.csv
        image_size: Resolution (128 for dev, 224 for final)
        batch_size: Batch size (32 default, 16 fallback)
        num_workers: DataLoader worker count (0 recommended on Windows)
        include_vertical_flip: Optional ablation flag
    """
    data_dir = Path(data_dir)
    
    train_transform = get_train_transforms(image_size=image_size, include_vertical_flip=include_vertical_flip)
    eval_transform = get_eval_transforms(image_size=image_size)

    train_ds = PlantVillageDataset(manifest_csv=data_dir / "train.csv", transform=train_transform)
    val_ds = PlantVillageDataset(manifest_csv=data_dir / "val.csv", transform=eval_transform)
    test_ds = PlantVillageDataset(manifest_csv=data_dir / "test.csv", transform=eval_transform)

    loaders = {
        "train": DataLoader(
            train_ds,
            batch_size=batch_size,
            shuffle=True,
            num_workers=num_workers,
            pin_memory=False
        ),
        "val": DataLoader(
            val_ds,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=False
        ),
        "test": DataLoader(
            test_ds,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=False
        )
    }

    return loaders
